import React, { forwardRef } from 'react'

// Geometry tests need Lucide's SVG box model, not its package-wide icon graph.
// Keeping this fixture-local component focused avoids a slow cold transform while
// preserving each control's computed size and all geometry assertions.
const GeometryIcon = forwardRef(function GeometryIcon({ color = 'currentColor', size = 24, strokeWidth = 2, ...props }, ref) {
  return React.createElement(
    'svg',
    {
      fill: 'none',
      height: size,
      ref,
      stroke: color,
      strokeLinecap: 'round',
      strokeLinejoin: 'round',
      strokeWidth,
      viewBox: '0 0 24 24',
      width: size,
      xmlns: 'http://www.w3.org/2000/svg',
      ...props,
    },
    React.createElement('path', { d: 'M4 12h16' }),
  )
})

